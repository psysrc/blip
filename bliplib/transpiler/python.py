import ast

from bliplib.errors import TranspilerError
from bliplib.transpiler.interface import Transpiler

# The `input` Blip identifier would shadow the Python `input` builtin function if we used it blindly
# So ideally we should convert `input` to another name when transpiling to Python
_input_identifier = "input_strs"

_function_name = "blip_autogenerated_function"


class UnknownType:
    """Placeholder for an expression whose Blip type the transpiler cannot determine yet."""


# Static scaffolding is written as Python source and parsed, rather than built node-by-node.
# None of it is derived from BlipIR, so there is nothing to escape, and it is far easier to read this way.
_FUNCTION_SCAFFOLD = f"""\
def {_function_name}({_input_identifier}: list[str]) -> list[str]:
    pass
"""

_PROGRAM_IMPORTS = """\
import argparse
import sys
import json
"""

_PROGRAM_MAIN = f"""\
def main():
    argument_parser = argparse.ArgumentParser()
    argument_parser.add_argument("input_strings", nargs="*", help="Input strings")

    args = argument_parser.parse_args()

    try:
        input_strings: list[str] = args.input_strings
        output_strings: list[str] = {_function_name}(input_strings)
        print(json.dumps(output_strings))
        sys.exit(0)

    except Exception as err:
        print(f"Error: {{err}}", file=sys.stderr)
        sys.exit(1)
"""

_PROGRAM_ENTRYPOINT = """\
if __name__ == "__main__":
    main()
"""


def _unparse(nodes: list[ast.stmt]) -> str:
    """Serialise a list of top-level statements into Python source code."""

    module = ast.Module(body=nodes, type_ignores=[])
    return ast.unparse(ast.fix_missing_locations(module))


class PythonStatement:
    def node(self) -> ast.stmt:
        raise NotImplementedError()


class PythonExpression:
    def __init__(self, node: ast.expr, expr_type: type):
        self.__node = node
        self.__expr_type = expr_type

    @staticmethod
    def from_blip_ir(blip_ir: dict) -> "PythonExpression":
        match blip_ir:
            case {"type": "string_literal"}:
                return PythonExpression(ast.Constant(value=blip_ir["value"]), str)

            case {"type": "list"}:
                elements = [PythonExpression.from_blip_ir(element) for element in blip_ir["elements"]]
                return PythonExpression(ast.List(elts=[element.node() for element in elements]), list)

            case {"type": "identifier"}:
                name = blip_ir["name"]

                # If this is the `input` identifier, change it
                if name == "input":
                    return PythonExpression(ast.Name(id=_input_identifier), list)

                return PythonExpression(ast.Name(id=name), UnknownType)

            case _:
                err = f"Cannot generate Python expression from BlipIR: {blip_ir}"
                raise TranspilerError(err)

    def node(self) -> ast.expr:
        return self.__node

    def get_type(self) -> type:
        return self.__expr_type


class PythonRaiseStatement(PythonStatement):
    def __init__(self, message: str):
        self.__message = message

    def node(self) -> ast.stmt:
        error = ast.Call(func=ast.Name(id="RuntimeError"), args=[ast.Constant(value=self.__message)], keywords=[])
        return ast.Raise(exc=error)


class PythonReturnStatement(PythonStatement):
    def __init__(self, expression: PythonExpression):
        self.__expression = expression

    @staticmethod
    def from_blip_ir(blip_ir: dict) -> "PythonReturnStatement":
        match blip_ir:
            case {"type": "return"}:
                expr = blip_ir["expression"]
                expression = PythonExpression.from_blip_ir(expr)
                return PythonReturnStatement(expression)

            case _:
                err = f"Cannot generate Python return statement from BlipIR: {blip_ir}"
                raise TranspilerError(err)

    def node(self) -> ast.stmt:
        value = self.__expression.node()

        if self.__expression.get_type() is str:
            value = ast.List(elts=[value])  # Wrap in a list

        return ast.Return(value=value)


class PythonFunction:
    def __init__(self, statements: list[PythonStatement]):
        self.__statements = statements

    def node(self) -> ast.stmt:
        function = ast.parse(_FUNCTION_SCAFFOLD).body[0]

        if not isinstance(function, ast.FunctionDef):
            raise TranspilerError("Internal error: the function scaffold is not a function definition")

        function.body = [stmt.node() for stmt in self.__statements]
        return function

    def serialise(self) -> str:
        return _unparse([self.node()])


class PythonTranspiler(Transpiler):
    def __build_function(self, blip_ir: dict) -> PythonFunction:
        try:
            blip_statements = blip_ir["statements"]

            if len(blip_statements) == 0:
                return PythonFunction([PythonRaiseStatement("Autogenerated Blip code halted without returning a value")])

            return PythonFunction([PythonReturnStatement.from_blip_ir(stmt) for stmt in blip_statements])

        except TranspilerError:
            raise

        except Exception as err:
            raise TranspilerError("Internal error") from err

    def transpile_function(self, blip_ir: dict) -> str:
        return self.__build_function(blip_ir).serialise()

    def transpile_program(self, blip_ir: dict) -> str:
        function = self.__build_function(blip_ir)

        # Each chunk is unparsed on its own so that top-level definitions stay separated by blank lines
        chunks = [
            ast.parse(_PROGRAM_IMPORTS).body,
            [function.node()],
            ast.parse(_PROGRAM_MAIN).body,
            ast.parse(_PROGRAM_ENTRYPOINT).body,
        ]

        return "\n\n\n".join(_unparse(chunk) for chunk in chunks)
