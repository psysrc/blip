import ast

from bliplib.decomposition import describe_pattern, pattern_captures, pattern_regex
from bliplib.errors import TranspilerError
from bliplib.ir import (
    Assignment,
    BooleanLiteral,
    Concatenation,
    Decomposition,
    Identifier,
    Index,
    IntegerLiteral,
    ListLiteral,
    Program,
    Return,
    Statement,
    StringLiteral,
    Value,
)
from bliplib.ir.types import List, Scalar
from bliplib.transpiler.interface import Transpiler

# A Blip identifier must start with a letter, so a generated name beginning with an underscore cannot collide with one. That
# matters: `input` has to be renamed because it would shadow the Python builtin, and a Blip variable of whatever name we rename
# it to would otherwise quietly overwrite the parameter.
_INPUT = "_blip_input"

# Scratch name holding the result of the last decomposition. Each one assigns it afresh and reads it back immediately, so
# reusing the name is safe.
_MATCH = "_blip_match"

# A decomposition is a regex match, so the generated function needs `re`. The import goes inside the function body rather than
# beside the program's other imports, because `transpile_function` emits the function alone for a caller to drop into their own
# module - a function that needs something imported for it cannot be dropped anywhere.
_DECOMPOSITION_IMPORT = "import re"

_FUNCTION_NAME = "blip_autogenerated_function"

# Static scaffolding is written as Python source and parsed, rather than built node-by-node.
# None of it is derived from BlipIR, so there is nothing to escape, and it is far easier to read this way.
_FUNCTION_SCAFFOLD = f"""\
def {_FUNCTION_NAME}({_INPUT}: list[str]) -> list[str]:
    pass
"""

_PROGRAM_IMPORTS = """\
import argparse
import sys
import json
"""

_PROGRAM_MAIN = f"""\
def main():
    argument_parser = argparse.ArgumentParser()
    argument_parser.add_argument("input_strings", nargs="*", help="Input strings")

    args = argument_parser.parse_args()

    try:
        input_strings: list[str] = args.input_strings
        output_strings: list[str] = {_FUNCTION_NAME}(input_strings)
        print(json.dumps(output_strings))
        sys.exit(0)

    except Exception as err:
        print(f"Error: {{err}}", file=sys.stderr)
        sys.exit(1)
"""

_PROGRAM_ENTRYPOINT = """\
if __name__ == "__main__":
    main()
"""

_NO_RETURN_MESSAGE = "Autogenerated Blip code halted without returning a value"


def _unparse(nodes: list[ast.stmt]) -> str:
    """Serialise a list of top-level statements into Python source code."""

    module = ast.Module(body=nodes, type_ignores=[])
    return ast.unparse(ast.fix_missing_locations(module))


def _python_name(blip_name: str) -> str:
    """The Python name for a Blip variable."""

    return _INPUT if blip_name == "input" else blip_name


def _load(name: str) -> ast.Name:
    return ast.Name(id=name, ctx=ast.Load())


def _store(name: str) -> ast.Name:
    return ast.Name(id=name, ctx=ast.Store())


def _raise(message: str) -> ast.stmt:
    error = ast.Call(func=_load("RuntimeError"), args=[ast.Constant(value=message)], keywords=[])
    return ast.Raise(exc=error)


def _expression(value: Value) -> ast.expr:
    """Lower a Blip value into a Python expression."""

    match value:
        case StringLiteral() | IntegerLiteral() | BooleanLiteral():
            return ast.Constant(value=value.value)

        case Identifier():
            return _load(_python_name(value.name))

        case Concatenation():
            operands = [_expression(operand) for operand in value.operands]

            # Blip concatenates by juxtaposition; Python needs the operator spelled out
            concatenated = operands[0]
            for operand in operands[1:]:
                concatenated = ast.BinOp(left=concatenated, op=ast.Add(), right=operand)

            return concatenated

        case Index():
            return ast.Subscript(value=_expression(value.target), slice=_expression(value.index), ctx=ast.Load())

        case ListLiteral():
            return ast.List(elts=[_expression(element) for element in value.elements], ctx=ast.Load())


def _return(statement: Return) -> ast.stmt:
    """
    Lower a Blip `ret` into a Python `return`.

    The generated function always returns a list of strings, so a program returning a single string has it wrapped. Before the
    analyser existed this was a guess, with an `UnknownType` escape hatch for the cases the transpiler could not work out. It is
    now a lookup: the analyser has already decided, and a type it cannot be is a bug rather than something to accommodate.
    """

    returned = _expression(statement.expression)

    match statement.expression.blip_type:
        case Scalar.STRING:
            return ast.Return(value=ast.List(elts=[returned], ctx=ast.Load()))

        case List(element=Scalar.STRING):
            return ast.Return(value=returned)

        case unreturnable:
            raise TranspilerError(f"A Blip program cannot return '{unreturnable}'")


def _decomposition(statement: Decomposition) -> list[ast.stmt]:
    """
    Lower a Blip decomposition into a Python regex match.

    The pattern is static, so the regex is built here at transpile time and only the match itself happens at run time.
    """

    pattern = statement.pattern
    target = _python_name(statement.target.name)

    matched = ast.Call(
        func=ast.Attribute(value=_load("re"), attr="fullmatch", ctx=ast.Load()),
        args=[ast.Constant(value=pattern_regex(pattern)), _load(target)],
        keywords=[ast.keyword(arg="flags", value=ast.Attribute(value=_load("re"), attr="DOTALL", ctx=ast.Load()))],
    )

    failed = ast.Compare(left=_load(_MATCH), ops=[ast.Is()], comparators=[ast.Constant(value=None)])
    message = f"Decomposition failed: '{statement.target.name}' does not match the pattern '{describe_pattern(pattern)}'"

    statements: list[ast.stmt] = [
        ast.Assign(targets=[_store(_MATCH)], value=matched),
        ast.If(test=failed, body=[_raise(message)], orelse=[]),
    ]

    # Binding every capture only after the match has been checked is what makes a failed decomposition leave the variables alone
    for group, name in enumerate(pattern_captures(pattern), start=1):
        captured = ast.Call(
            func=ast.Attribute(value=_load(_MATCH), attr="group", ctx=ast.Load()),
            args=[ast.Constant(value=group)],
            keywords=[],
        )
        statements.append(ast.Assign(targets=[_store(_python_name(name))], value=captured))

    return statements


def _statement(statement: Statement) -> list[ast.stmt]:
    """Lower one Blip statement. A decomposition becomes several Python statements; everything else becomes one."""

    match statement:
        case Assignment():
            target = _store(_python_name(statement.target.name))
            return [ast.Assign(targets=[target], value=_expression(statement.expression))]

        case Return():
            return [_return(statement)]

        case Decomposition():
            return _decomposition(statement)


class PythonFunction:
    def __init__(self, program: Program):
        self.__program = program

    def node(self) -> ast.stmt:
        function = ast.parse(_FUNCTION_SCAFFOLD).body[0]

        if not isinstance(function, ast.FunctionDef):
            raise TranspilerError("Internal error: the function scaffold is not a function definition")

        body: list[ast.stmt] = []

        if any(isinstance(statement, Decomposition) for statement in self.__program.statements):
            body += ast.parse(_DECOMPOSITION_IMPORT).body

        for statement in self.__program.statements:
            body += _statement(statement)

        # A Blip program that can run off the end never returned a value, which is an error at execution time rather than a
        # static one. An empty program is just the simplest case of that.
        if not self.__program.statements or not isinstance(self.__program.statements[-1], Return):
            body.append(_raise(_NO_RETURN_MESSAGE))

        function.body = body
        return function

    def serialise(self) -> str:
        return _unparse([self.node()])


class PythonTranspiler(Transpiler):
    def __build_function(self, program: Program) -> PythonFunction:
        return PythonFunction(program)

    def transpile_function(self, program: Program) -> str:
        return self.__build_function(program).serialise()

    def transpile_program(self, program: Program) -> str:
        function = self.__build_function(program)

        # Each chunk is unparsed on its own so that top-level definitions stay separated by blank lines
        chunks = [
            ast.parse(_PROGRAM_IMPORTS).body,
            [function.node()],
            ast.parse(_PROGRAM_MAIN).body,
            ast.parse(_PROGRAM_ENTRYPOINT).body,
        ]

        return "\n\n\n".join(_unparse(chunk) for chunk in chunks)
