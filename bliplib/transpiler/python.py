import ast
from collections.abc import Sequence

from bliplib.decomposition import describe_pattern, pattern_captures, pattern_regex
from bliplib.errors import TranspilerError
from bliplib.ir import (
    Assignment,
    BooleanLiteral,
    Concatenation,
    Decomposition,
    DecompPattern,
    DecompTest,
    Directive,
    FixedDirective,
    Identifier,
    If,
    Index,
    IntegerLiteral,
    ListLiteral,
    Program,
    RangeDirective,
    Return,
    Statement,
    StringLiteral,
    Value,
)
from bliplib.ir.types import List, Scalar
from bliplib.transpiler.interface import Transpiler

# A Blip identifier must start with a letter, so a generated name beginning with an underscore cannot collide with one. That
# matters: `input` has to be renamed because it would shadow the Python builtin, and a Blip variable of whatever name we rename
# it to would otherwise quietly overwrite the parameter.
_INPUT = "_blip_input"

# Scratch name holding the result of the last decomposition. Each one assigns it afresh and reads it back immediately, so
# reusing the name is safe - including for a decomposition nested inside the block another one guards, because the outer
# captures are all bound before the block that could reassign this runs.
_MATCH = "_blip_match"

# Scratch name holding the value a `ret` produced, so that an output directive can measure it before it is handed back. Only
# emitted when there is an output directive to check.
_OUTPUT = "_blip_output"

# A decomposition is a regex match, so the generated function needs `re`. The import goes inside the function body rather than
# beside the program's other imports, because `transpile_function` emits the function alone for a caller to drop into their own
# module - a function that needs something imported for it cannot be dropped anywhere.
_DECOMPOSITION_IMPORT = "import re"

_FUNCTION_NAME = "blip_autogenerated_function"

# Static scaffolding is written as Python source and parsed, rather than built node-by-node.
# None of it is derived from BlipIR, so there is nothing to escape, and it is far easier to read this way.
_FUNCTION_SCAFFOLD = f"""\
def {_FUNCTION_NAME}({_INPUT}: list[str]) -> list[str]:
    pass
"""

_PROGRAM_IMPORTS = """\
import argparse
import sys
import json
"""

_PROGRAM_MAIN = f"""\
def main():
    argument_parser = argparse.ArgumentParser()
    argument_parser.add_argument("input_strings", nargs="*", help="Input strings")

    args = argument_parser.parse_args()

    try:
        input_strings: list[str] = args.input_strings
        output_strings: list[str] = {_FUNCTION_NAME}(input_strings)
        print(json.dumps(output_strings))
        sys.exit(0)

    except Exception as err:
        print(f"Error: {{err}}", file=sys.stderr)
        sys.exit(1)
"""

_PROGRAM_ENTRYPOINT = """\
if __name__ == "__main__":
    main()
"""

_NO_RETURN_MESSAGE = "Autogenerated Blip code halted without returning a value"


def _unparse(nodes: list[ast.stmt]) -> str:
    """Serialise a list of top-level statements into Python source code."""

    module = ast.Module(body=nodes, type_ignores=[])
    return ast.unparse(ast.fix_missing_locations(module))


def _python_name(blip_name: str) -> str:
    """The Python name for a Blip variable."""

    return _INPUT if blip_name == "input" else blip_name


def _load(name: str) -> ast.Name:
    return ast.Name(id=name, ctx=ast.Load())


def _store(name: str) -> ast.Name:
    return ast.Name(id=name, ctx=ast.Store())


def _raise(message: str | ast.expr) -> ast.stmt:
    """A `raise RuntimeError()` statement."""

    if isinstance(message, str):
        message = ast.Constant(value=message)

    error = ast.Call(func=_load("RuntimeError"), args=[message], keywords=[])
    return ast.Raise(exc=error)


def _length(operands: ast.expr) -> ast.expr:
    """A `len()` call."""

    return ast.Call(func=_load("len"), args=[operands], keywords=[])


def _arity_guard(operands: ast.expr, in_or_out: str, comparison: ast.cmpop, bound: int, description: str) -> ast.stmt:
    """One `if len(...) <op> N: raise` guard."""

    failed = ast.Compare(left=_length(operands), ops=[comparison], comparators=[ast.Constant(value=bound)])

    message = ast.JoinedStr(
        values=[
            ast.Constant(value=f"Program {in_or_out} validation failed: Directive expected {description}, got "),
            ast.FormattedValue(value=_length(operands), conversion=-1),
        ]
    )

    return ast.If(test=failed, body=[_raise(message)], orelse=[])


def _arity_guards(operands: ast.expr, reason: str, directive: Directive) -> list[ast.stmt]:
    """Lower a directive into the `if` guards that enforce it."""

    match directive:
        case FixedDirective(count=count):
            return [_arity_guard(operands, reason, ast.NotEq(), count, f"{count} operands")]

        case RangeDirective(min=minimum, max=maximum):
            guards: list[ast.stmt] = []

            if minimum is not None:
                guards.append(_arity_guard(operands, reason, ast.Lt(), minimum, f"at least {minimum} operands"))

            if maximum is not None:
                guards.append(_arity_guard(operands, reason, ast.Gt(), maximum, f"at most {maximum} operands"))

            return guards


def _input_bindings(directive: Directive) -> list[ast.stmt]:
    """A named input directive gives each input string a name. A counted or ranged one names nothing."""

    match directive:
        case FixedDirective(names=[*names]):
            return [
                ast.Assign(
                    targets=[_store(_python_name(name))],
                    value=ast.Subscript(value=_load(_INPUT), slice=ast.Constant(value=index), ctx=ast.Load()),
                )
                for index, name in enumerate(names)
            ]

        case _:
            return []


def _expression(value: Value) -> ast.expr:
    """Lower a Blip value into a Python expression."""

    match value:
        case StringLiteral() | IntegerLiteral() | BooleanLiteral():
            return ast.Constant(value=value.value)

        case Identifier():
            return _load(_python_name(value.name))

        case Concatenation():
            operands = [_expression(operand) for operand in value.operands]

            # Blip concatenates by juxtaposition; Python needs the operator spelled out
            concatenated = operands[0]
            for operand in operands[1:]:
                concatenated = ast.BinOp(left=concatenated, op=ast.Add(), right=operand)

            return concatenated

        case Index():
            return ast.Subscript(value=_expression(value.target), slice=_expression(value.index), ctx=ast.Load())

        case ListLiteral():
            return ast.List(elts=[_expression(element) for element in value.elements], ctx=ast.Load())


def _return(statement: Return, output: Directive | None) -> list[ast.stmt]:
    """Lower a Blip `ret` into a Python `return`."""

    returned = _expression(statement.expression)

    match statement.expression.blip_type:
        case Scalar.STRING:
            outputs: ast.expr = ast.List(elts=[returned], ctx=ast.Load())

        case List(element=Scalar.STRING):
            outputs = returned

        case unreturnable:
            raise TranspilerError(f"A Blip program cannot return '{unreturnable}'")

    guards = _arity_guards(_load(_OUTPUT), "output", output) if output is not None else []

    if not guards:
        return [ast.Return(value=outputs)]

    return [
        ast.Assign(targets=[_store(_OUTPUT)], value=outputs),
        *guards,
        ast.Return(value=_load(_OUTPUT)),
    ]


def _decomposition_match(target: Identifier, pattern: DecompPattern) -> ast.stmt:
    """
    The `re.fullmatch` both forms of decomposition begin with.

    The pattern is static, so the regex is built here at transpile time and only the match itself happens at run time.
    """

    matched = ast.Call(
        func=ast.Attribute(value=_load("re"), attr="fullmatch", ctx=ast.Load()),
        args=[ast.Constant(value=pattern_regex(pattern)), _load(_python_name(target.name))],
        keywords=[ast.keyword(arg="flags", value=ast.Attribute(value=_load("re"), attr="DOTALL", ctx=ast.Load()))],
    )

    return ast.Assign(targets=[_store(_MATCH)], value=matched)


def _match_is(comparison: ast.cmpop) -> ast.expr:
    """A test of the last match against `None`, which is how the regex module reports a failure."""

    return ast.Compare(left=_load(_MATCH), ops=[comparison], comparators=[ast.Constant(value=None)])


def _capture_bindings(pattern: DecompPattern) -> list[ast.stmt]:
    """
    Read each captured group out of the match and into the variable that named it.

    Emitted only where the match is already known to have succeeded, which is what makes a failed decomposition leave the
    variables as they were - for a statement, which raises instead, and for a condition, whose `else` branch then runs with
    nothing bound.
    """

    bindings: list[ast.stmt] = []

    for name in pattern_captures(pattern):
        captured = ast.Call(
            func=ast.Attribute(value=_load(_MATCH), attr="group", ctx=ast.Load()),
            args=[ast.Constant(value=name)],
            keywords=[],
        )
        bindings.append(ast.Assign(targets=[_store(_python_name(name))], value=captured))

    return bindings


def _decomposition(statement: Decomposition) -> list[ast.stmt]:
    """Lower a Blip decomposition statement, which halts the program when the string does not fit the pattern."""

    pattern = statement.pattern
    message = f"Decomposition failed: '{statement.target.name}' does not match the pattern '{describe_pattern(pattern)}'"

    return [
        _decomposition_match(statement.target, pattern),
        ast.If(test=_match_is(ast.Is()), body=[_raise(message)], orelse=[]),
        *_capture_bindings(pattern),
    ]


def _lower(statements: Sequence[Statement], output: Directive | None) -> list[ast.stmt]:
    """Lower a run of Blip statements, flattening the several Python statements that some of them each become."""

    return [node for statement in statements for node in _statement(statement, output)]


def _block(lowered: list[ast.stmt]) -> list[ast.stmt]:
    """A Python block, which unlike in Blip, cannot be empty."""

    return lowered or [ast.Pass()]


def _if(statement: If, output: Directive | None) -> list[ast.stmt]:
    """Lower a Blip `if` into a Python `if`."""

    orelse = _lower(statement.otherwise or [], output)

    match statement.condition:
        case DecompTest() as test:
            succeeded = _block([*_capture_bindings(test.pattern), *_lower(statement.body, output)])

            return [
                _decomposition_match(test.target, test.pattern),
                ast.If(test=_match_is(ast.IsNot()), body=succeeded, orelse=orelse),
            ]

        case condition:
            return [ast.If(test=_expression(condition), body=_block(_lower(statement.body, output)), orelse=orelse)]


def _needs_regex(statements: Sequence[Statement]) -> bool:
    """Whether anything in these statements is a decomposition, at any depth."""

    for statement in statements:
        match statement:
            case Decomposition():
                return True

            case If():
                if isinstance(statement.condition, DecompTest):
                    return True

                if _needs_regex(statement.body) or _needs_regex(statement.otherwise or []):
                    return True

            case _:
                continue

    return False


def _statement(statement: Statement, output: Directive | None) -> list[ast.stmt]:
    """Lower one Blip statement. A decomposition, an `if` or a checked `ret` becomes several Python statements; an assignment one."""

    match statement:
        case Assignment():
            target = _store(_python_name(statement.target.name))
            return [ast.Assign(targets=[target], value=_expression(statement.expression))]

        case Return():
            return _return(statement, output)

        case Decomposition():
            return _decomposition(statement)

        case If():
            return _if(statement, output)


class PythonFunction:
    def __init__(self, program: Program):
        self.__program = program

    def node(self) -> ast.stmt:
        function = ast.parse(_FUNCTION_SCAFFOLD).body[0]

        if not isinstance(function, ast.FunctionDef):
            raise TranspilerError("Internal error: the function scaffold is not a function definition")

        directives = self.__program.directives
        declared_input = directives.input if directives is not None else None
        declared_output = directives.output if directives is not None else None

        body: list[ast.stmt] = []

        if _needs_regex(self.__program.statements):
            body += ast.parse(_DECOMPOSITION_IMPORT).body

        if declared_input is not None:
            body += _arity_guards(_load(_INPUT), "input", declared_input)
            body += _input_bindings(declared_input)

        body += _lower(self.__program.statements, declared_output)

        # A Blip program that can run off the end never returned a value, which is an error at execution time rather than a
        # static one. An empty program is just the simplest case of that.
        #
        # The test is syntactic, so a program ending in an `if` whose every branch returns still gets this raise appended,
        # unreachable. Knowing better means definite-return analysis, which `docs/todo.md` keeps as its own feature.
        if not self.__program.statements or not isinstance(self.__program.statements[-1], Return):
            body.append(_raise(_NO_RETURN_MESSAGE))

        function.body = body
        return function

    def serialise(self) -> str:
        return _unparse([self.node()])


class PythonTranspiler(Transpiler):
    def __build_function(self, program: Program) -> PythonFunction:
        return PythonFunction(program)

    def transpile_function(self, program: Program) -> str:
        return self.__build_function(program).serialise()

    def transpile_program(self, program: Program) -> str:
        function = self.__build_function(program)

        # Each chunk is unparsed on its own so that top-level definitions stay separated by blank lines
        chunks = [
            ast.parse(_PROGRAM_IMPORTS).body,
            [function.node()],
            ast.parse(_PROGRAM_MAIN).body,
            ast.parse(_PROGRAM_ENTRYPOINT).body,
        ]

        return "\n\n\n".join(_unparse(chunk) for chunk in chunks)
