from typing import Self
from bliplib.transpiler.interface import Transpiler
from bliplib.errors import TranspilerError


# The `input` Blip identifier would shadow the Python `input` builtin function if we used it blindly
# So ideally we should convert `input` to another name when transpiling to Python
_input_identifier = "input_strs"


class PythonStatement:
    def serialise(self) -> str:
        raise NotImplementedError()


class PythonExpression:
    def __init__(self, expression: str, expr_type: type):
        self.__expression = expression
        self.__expr_type = expr_type

        # If this is the `input` identifier, change it
        if expression == "input" and expr_type == "identifier":
            self.__expression = _input_identifier

    @staticmethod
    def from_blip_ir(blip_ir: dict) -> Self:
        match blip_ir:
            case {"type": "expression"}:
                expr = blip_ir["value"]
                match expr:
                    case {"type": "string_literal"}:
                        return PythonExpression(f'"{expr["value"]}"', str)
                    case {"type": "list"}:
                        elems = expr["elements"]
                        values = [f'"{e["value"]["value"]}"' for e in elems]
                        return PythonExpression(f"[{', '.join(values)}]", list)
                    case {"type": "identifier"}:
                        return PythonExpression(f"{expr['name']}", "identifier")
                    case _:
                        raise NotImplementedError()

            case _:
                err = f"Cannot generate Python expression from BlipIR: {blip_ir}"
                raise TranspilerError(err)

    def serialise(self) -> str:
        return self.__expression

    def get_type(self) -> type:
        return self.__expr_type


class PythonRaiseStatement(PythonStatement):
    def __init__(self, message: str):
        self.__message = message

    def serialise(self) -> str:
        return f"""raise RuntimeError("{self.__message}")"""


class PythonReturnStatement(PythonStatement):
    def __init__(self, expression: PythonExpression):
        self.__expression = expression

    @staticmethod
    def from_blip_ir(blip_ir: dict) -> Self:
        match blip_ir:
            case {"type": "return"}:
                expr = blip_ir["expression"]
                expression = PythonExpression.from_blip_ir(expr)
                return PythonReturnStatement(expression)

            case _:
                err = f"Cannot generate Python return statement from BlipIR: {blip_ir}"
                raise TranspilerError(err)

    def serialise(self) -> str:
        expression = self.__expression.serialise()

        if self.__expression.get_type() is str:
            expression = f"[{expression}]"  # Wrap in a list

        return f"""return {expression}"""


class PythonFunction:
    def __init__(self, statements: list[PythonStatement]):
        self.__statements = statements

    def serialise(self) -> str:
        signature = f"""def blip_autogenerated_function({_input_identifier}: list[str]) -> list[str]:"""

        serial = [signature]

        for stmt in self.__statements:
            serial.append(f"    {stmt.serialise()}")

        return "\n".join(serial)


class PythonTranspiler(Transpiler):
    def transpile_function(self, blip_ir: dict) -> str:
        try:
            blip_statements = blip_ir["statements"]

            if len(blip_statements) == 0:
                function = PythonFunction([PythonRaiseStatement("Autogenerated Blip code halted without returning a value")])
            else:
                function = PythonFunction([PythonReturnStatement.from_blip_ir(stmt) for stmt in blip_statements])

            return function.serialise()

        except TranspilerError:
            raise

        except Exception as err:
            raise TranspilerError("Internal error") from err

    def transpile_program(self, blip_ir: dict) -> str:
        function = self.transpile_function(blip_ir)

        program_lines = [
            """import argparse""",
            """import sys""",
            """import json""",
            """""",
            """""",
            f"{function}",
            """""",
            """""",
            """def main():""",
            """    argument_parser = argparse.ArgumentParser()""",
            """    argument_parser.add_argument("input_strings", nargs="*", help="Input strings")""",
            """""",
            """    args = argument_parser.parse_args()""",
            """""",
            """    try:""",
            """        input_strings: list[str] = args.input_strings""",
            """        output_strings: list[str] = blip_autogenerated_function(input_strings)""",
            """        print(json.dumps(output_strings))""",
            """        sys.exit(0)""",
            """""",
            """    except Exception as err:""",
            """        print(f"Error: {err}", file=sys.stderr)""",
            """        sys.exit(1)""",
            """""",
            """""",
            """if __name__ == "__main__":""",
            """    main()""",
        ]

        return "\n".join(program_lines)
