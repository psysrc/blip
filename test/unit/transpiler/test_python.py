AWKWARD_STRINGS = [
    'double " quote',
    "single ' quote",
    "backslash \\ and \\n escape",
    "both \" and ' quotes",
    "newline \n in the middle",
    "tab \t and carriage return \r",
    'triple """ quotes',
    "unicode é中\U0001f600",
]


def test_string_literals_are_escaped():
    """Blip string literals must survive transpilation intact, whatever characters they contain."""

    for awkward in AWKWARD_STRINGS:
        blip_ir = {
            "type": "program",
            "statements": [
                {
                    "type": "return",
                    "expression": {"type": "expression", "value": {"type": "string_literal", "value": awkward}},
                }
            ],
        }

        actual_python = PythonTranspiler().transpile_function(blip_ir)

        # The generated function must parse, and calling it must give back the original string
        namespace: dict = {}
        exec(actual_python, namespace)  # noqa: S102
        assert namespace["blip_autogenerated_function"]([]) == [awkward], f"String was mangled: {awkward!r}"


def test_transpiled_program_is_valid_python():
    """Whatever the transpiler emits must at least be syntactically valid Python."""

    blip_ir = {
        "type": "program",
        "statements": [
            {
                "type": "return",
                "expression": {"type": "expression", "value": {"type": "string_literal", "value": 'awkward " string'}},
            }
        ],
    }

    ast.parse(PythonTranspiler().transpile_program(blip_ir))
